from pathlib import Path

Macro = tuple[str, str]


def newcommand(name: str, body: str) -> Macro:
    """Make a new macro."""
    return name, body


def starmacro(
    name: str, nostar: str, star: str | None = None
) -> tuple[Macro, ...]:
    """Make a macro with a star and a non-star mode."""
    left = ["(", "[", "\\lvert", "\\lVert", "\\langle", "\\lfloor", "\\lceil"]
    middle = ["|", "\\|", "\\vert", "\\Vert"]
    right = [")", "]", "\\rvert", "\\rVert", "\\rangle", "\\rfloor", "\\rceil"]
    if star is None:
        star = nostar
        for direction, delims in zip(
            ("\\left", "\\middle", "\\right"), (left, middle, right)
        ):
            for delim in delims:
                star = star.replace(delim, direction + delim)
        # HACK: fix \|
        star = star.replace(r"\\middle", r"\middle")
    return (
        (name, rf"\@ifstar{{\{name}@star}}{{\{name}@nostar}}"),
        (f"{name}@nostar", nostar),
        (f"{name}@star", star),
    )


def DeclarePairedDelimiter(
    name: str, left: str, right: str, body: str = "#1"
) -> tuple[Macro, ...]:
    """An emulator of the corresponding mathtools macro."""
    return starmacro(
        name, f"{left} {body} {right}", rf"\left{left} {body} \right{right}"
    )


